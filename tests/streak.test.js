const assert=require('node:assert/strict');
const {weekIndex,current,complete}=require('../streak.js');
const d=(y,m,day)=>new Date(y,m-1,day);
const sun=d(2026,11,8), mon=d(2026,11,9);
assert.equal(weekIndex(d(2026,11,2)),weekIndex(sun));
assert.equal(weekIndex(mon)-weekIndex(sun),1);
assert.equal(weekIndex(d(2027,1,3)),weekIndex(d(2026,12,28)));
assert.equal(weekIndex(d(2027,1,4))-weekIndex(d(2027,1,3)),1);
assert.equal(current(null,sun),0);
let r=complete(null,sun);assert.equal(r.count,1);
assert.deepEqual(complete(r,sun),r);
assert.equal(current(r,mon),1);
r=complete(r,mon);assert.equal(r.count,2);
assert.equal(current(r,d(2026,11,23)),0);
assert.equal(complete(r,d(2026,11,23)).count,1);
assert.equal(current({week:weekIndex(sun),count:-1},sun),0);
console.log('PASS: Monday–Sunday streak boundary, repeat, consecutive, gap and year rollover');
